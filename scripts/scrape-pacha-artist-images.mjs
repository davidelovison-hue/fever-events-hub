/**
 * Scrape artist portrait URLs from https://pacha.com/events (Next.js payload).
 * Run: node scripts/scrape-pacha-artist-images.mjs
 */
import { writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = dirname(fileURLToPath(import.meta.url))
const OUT = join(__dirname, '../src/pachaArtistImages.generated.ts')

const EVENTS_URL = 'https://pacha.com/events'
const ARTISTS_URL = 'https://pacha.com/artists'

function decodeName(raw) {
  return raw.replace(/u0026/g, '&').replace(/\\&/g, '&').trim()
}

function extractArtistRecords(html) {
  const re =
    /\{\\"id\\":(\d+),\\"slug\\":\\"([^\\]+)\\",\\"name\\":\\"([^\\]+)\\",\\"image_url\\":\\"(https?:\/\/[^\\]+)\\"\}/g
  const map = new Map()
  for (const m of html.matchAll(re)) {
    const name = decodeName(m[3])
    const image = m[4].replace(/\\\//g, '/')
    const slug = m[2]
    const key = name.toLowerCase()
    if (!map.has(key)) map.set(key, { name, slug, image })
  }
  return map
}

function extractResidences(html) {
  const re =
    /\\"name\\":\\"([^\\]+)\\",\\"slug\\":\\"([^\\]+)\\",\\"itemId\\":\\"([^\\]+)\\",\\"residencesImage\\":\\"(https:\/\/pacha-production[^\\]+)\\"/g
  const map = new Map()
  for (const m of html.matchAll(re)) {
    const name = decodeName(m[1])
    map.set(name.toLowerCase(), { name, slug: m[2], image: m[3] })
  }
  return map
}

async function fetchText(url) {
  const res = await fetch(url, {
    headers: { 'user-agent': 'Mozilla/5.0 (compatible; fever-events-hub/1.0)' },
  })
  if (!res.ok) throw new Error(`${url} → ${res.status}`)
  return res.text()
}

const [eventsHtml, artistsHtml] = await Promise.all([
  fetchText(EVENTS_URL),
  fetchText(ARTISTS_URL),
])

const artists = extractArtistRecords(eventsHtml)
const residences = extractResidences(artistsHtml)

const merged = new Map(artists)
for (const [key, row] of residences) {
  if (!merged.has(key)) merged.set(key, { name: row.name, slug: row.slug, image: row.image })
}

const list = [...merged.values()].sort((a, b) => a.name.localeCompare(b.name))

const body = `/* eslint-disable */
/** Auto-generated by scripts/scrape-pacha-artist-images.mjs — do not edit by hand. */
export type PachaArtistImageRow = { name: string; slug: string; image: string }

export const PACHA_ARTIST_IMAGE_ROWS: PachaArtistImageRow[] = ${JSON.stringify(list, null, 2)}
`

writeFileSync(OUT, body)
console.log(`Wrote ${list.length} artist images → ${OUT}`)
